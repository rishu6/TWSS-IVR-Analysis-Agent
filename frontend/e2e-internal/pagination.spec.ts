import {test,expect} from '@playwright/test';
test('independent page sizes across tabs',async({page})=>{
  await page.goto('/');
  await expect(page).toHaveTitle(/TWSS IVR/);
  await expect(page.getByRole('heading',{name:'Sign in to your account'})).toBeVisible();
  await expect(page.getByLabel('Demo role')).toHaveCount(0);
  await page.getByLabel('Username',{exact:true}).fill('browseradmin');
  await page.getByLabel('Password',{exact:true}).fill('fixture-temporary-password');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Set your password'})).toBeVisible();
  await page.getByLabel('Temporary / current password').fill('fixture-temporary-password');
  await page.getByLabel('New password · at least 12 characters').fill('fixture-replacement-password');
  await page.getByLabel('Confirm new password').fill('fixture-replacement-password');
  await page.getByRole('button',{name:'Save password and continue'}).click();
  await expect(page.getByRole('heading',{name:'Analysis dashboard'})).toBeVisible();
  await page.goto('/flows?page=2');
  await page.getByLabel('Rows per page',{exact:true}).selectOption('all');
  await expect(page).not.toHaveURL(/[?&]page=2/);
  await expect(page.getByRole('button',{name:'Expand flow',exact:true})).toHaveCount(3);
  await expect(page.getByRole('button',{name:'Next',exact:true})).toBeDisabled();
  await page.getByLabel('Rows per page',{exact:true}).selectOption('50');
  await page.goto('/crm');
  await expect(page.getByLabel('Rows per page',{exact:true})).toHaveValue('10');
  await page.getByLabel('Rows per page',{exact:true}).selectOption('25');
  await page.reload();
  await expect(page.getByLabel('Rows per page',{exact:true})).toHaveValue('25');
  await page.goto('/admin');
  await expect(page.getByLabel('Rows per page',{exact:true})).toHaveValue('10');
  await page.getByLabel('Rows per page',{exact:true}).selectOption('100');
  await page.goto('/live');
  await expect(page.getByLabel('Rows per page',{exact:true})).toHaveValue('10');
  await page.goto('/flows');
  await expect(page.getByLabel('Rows per page',{exact:true})).toHaveValue('50');
});
