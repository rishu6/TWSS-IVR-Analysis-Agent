import {test,expect} from '@playwright/test';
test.use({baseURL:'http://127.0.0.1:8003'});
test('weekly patterns show real totals, hourly focus and independent week filters',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/');await page.getByRole('button',{name:'Enter demo workspace'}).click();
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Call patterns',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Call patterns',exact:true})).toBeVisible();
 await expect(page.locator('.patterns-kpis article')).toHaveCount(3);
 await expect(page.locator('.patterns-kpis article').first()).toContainText('Tuesday');
 const table=page.getByRole('table',{name:'Calls by weekday and hour'});
 await expect(table.getByRole('button')).toHaveCount(168);
 await table.getByRole('button',{name:'Tuesday 10:00–11:00 IST: 5 calls',exact:true}).click();
 await expect(page.getByLabel('Weekday for hourly calls')).toHaveValue('1');
 await expect(page.locator('.patterns-heatmap [role=status]')).toContainText('5 calls');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'/private/tmp/twss-call-patterns-light.png',fullPage:true});
 await page.getByRole('button',{name:'Dark theme',exact:true}).click();
 await page.screenshot({path:'/private/tmp/twss-call-patterns-dark.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:'/private/tmp/twss-call-patterns-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'Last week',exact:true}).click();
 await expect(page).toHaveURL(/start=/);
 const start=new URL(page.url()).searchParams.get('start')!;
 const end=new URL(page.url()).searchParams.get('end')!;
 expect((Date.parse(end)-Date.parse(start))/86400000).toBe(7);
 expect(new Intl.DateTimeFormat('en-US',{timeZone:'Asia/Kolkata',weekday:'long'}).format(new Date(start))).toBe('Monday');
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Overview',exact:true}).click();
 await expect(page.getByLabel('Report from date')).toHaveValue('');
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Call patterns',exact:true}).click();
 expect(new URL(page.url()).searchParams.get('start')).toBe(start);
 await page.getByLabel('Report from date').fill('2025-01-01');
 await page.getByLabel('Report through date').fill('2025-01-01');
 await page.getByRole('button',{name:'Apply filters',exact:true}).click();
 await expect(page.getByText('No calls with a recorded time match these filters. Try another date range.')).toBeVisible();
 expect(errors).toEqual([]);
});
