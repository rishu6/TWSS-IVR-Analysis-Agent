import {test,expect} from '@playwright/test';
test.use({baseURL:'http://127.0.0.1:8003'});
test('executive dashboard charts, themes and filtered drilldowns',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto('/');
  await page.getByRole('button',{name:'Enter demo workspace'}).click();
  await expect(page.getByRole('heading',{name:'Analysis dashboard',exact:true})).toBeVisible();
  await expect(page.locator('.dash-kpi')).toHaveCount(6);
  const metrics=await (await page.request.get('/api/v1/metrics/overview')).json();
  await expect(page.locator('.dash-kpi').filter({hasText:'Unique callers'}).locator(':scope > strong')).toHaveText(String(metrics.unique_callers));
  await expect(page.getByRole('heading',{name:'When are customers calling?'})).toBeVisible();
  await expect(page.locator('.dash-chart .recharts-surface')).toBeVisible();
  await expect(page.locator('.dash-dept-row').first()).toBeVisible();
  await expect(page.locator('.dash-donut .recharts-pie-sector').first()).toBeVisible();
  await page.screenshot({path:'/private/tmp/twss-analysis-light.png',fullPage:true});
  await page.getByRole('button',{name:'Lines',exact:true}).click();
  await expect(page.locator('.dash-chart .recharts-area').first()).toBeVisible();
  await page.getByLabel('Trend grouping').selectOption('day');
  await expect(page.locator('.dash-unit')).toHaveText('By day · IST');
  await page.getByLabel('Sort departments').selectOption('missed');
  await page.evaluate(()=>{document.documentElement.dataset.theme='dark';document.documentElement.dataset.palette='soft-charcoal';document.documentElement.style.colorScheme='dark';});
  await page.screenshot({path:'/private/tmp/twss-analysis-dark.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'Analysis dashboard',exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({path:'/private/tmp/twss-analysis-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1050});
  await page.locator('.dash-kpi').filter({hasText:'Customer missed'}).click();
  await expect(page).toHaveURL(/outcome=MISSED/);
  await expect(page).toHaveURL(/missed_department=true/);
  await expect(page.getByRole('heading',{name:'Answered and missed call journeys'})).toBeVisible();
  await page.goto('/');
  const rate=page.locator('.dash-kpi').filter({hasText:'Answer rate'});
  await expect(rate.locator(':scope > strong')).toHaveText((metrics.answer_rate*100).toFixed(1)+'%');
  await expect(rate).toContainText(`${metrics.department_answered} of ${metrics.department_calls} department calls`);
  await rate.click();
  await expect(page).toHaveURL(/department_selected=true/);
  await expect(page).toHaveURL(/outcome=ANSWERED/);
  expect(errors).toEqual([]);
});
