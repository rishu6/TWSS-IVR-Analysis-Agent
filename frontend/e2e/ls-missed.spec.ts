import {test,expect} from '@playwright/test';
test.use({baseURL:'http://127.0.0.1:8003'});
test('missed calls offer a department-selected subsection and preserve other filters',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'Enter demo workspace'}).click();
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'LeadSquared insights',exact:true}).click();
 await page.getByLabel('Report from date').fill('2026-10-27');
 await page.getByLabel('Report through date').fill('2026-10-27');
 await page.getByLabel('Call status',{exact:true}).selectOption('MISSED');
 await page.getByRole('button',{name:'Apply filters',exact:true}).click();
 const section=page.getByRole('region',{name:'Missed call breakdown'});
 await expect(section).toBeVisible();
 const expected=await (await page.request.get('/api/v1/reports/leadsquared?outcome=MISSED&department_selected=false')).json();
 await expect(section.getByRole('button',{name:/All missed calls/})).toContainText(String(expected.selection_counts.all_calls));
 const start=new URL(page.url()).searchParams.get('start');
 await section.getByRole('button',{name:/Missed after department selection/}).click();
 await expect(section.getByRole('button',{name:/Missed after department selection/})).toHaveAttribute('aria-pressed','true');
 await expect(page).toHaveURL(/department_selected=true/);
 expect(new URL(page.url()).searchParams.get('start')).toBe(start);
 await expect(page.locator('.crm-summary .kpi').first()).toContainText('Missed after department selection');
 await expect(page.locator('.crm-summary .kpi').first().locator(':scope > strong')).toHaveText(String(expected.selection_counts.department_calls));
 await section.getByRole('button',{name:/All missed calls/}).click();
 await expect(section.getByRole('button',{name:/All missed calls/})).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('.crm-summary .kpi').first()).toContainText('Missed calls');
 await page.getByLabel('Call status',{exact:true}).selectOption('ANSWERED');
 await page.getByRole('button',{name:'Apply filters',exact:true}).click();
 await expect(section).toHaveCount(0);
 expect(errors).toEqual([]);
});
